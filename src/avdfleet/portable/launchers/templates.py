"""Cross-platform launcher file templates.

The generated launchers are intentionally thin: they derive the bundle root from
their own location (so they survive relocation), perform the platform-specific
first-run hygiene (Windows Mark-of-the-Web removal, macOS quarantine warning,
Linux execute-bit repair), export the portable environment and then hand over to
``python -m avdfleet.portable.launchers.generator start`` which starts
``avdfleet serve --portable``, waits for ``/health`` and opens the browser.

Encoding rules (asserted by :func:`validate_launcher`):

* Windows ``.cmd``: pure ASCII, CRLF line endings (cmd.exe's default code page
  would otherwise mangle non-ASCII characters).
* macOS ``.command`` / Linux ``.sh``: UTF-8 **without** BOM, LF line endings
  (a BOM would break the shebang; CRLF breaks the interpreter path).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from avdfleet.core.config import APP_VERSION
from avdfleet.portable.env.model import host_os_name

WINDOWS_LAUNCHER_FILENAME = "AVD Fleet.cmd"
MACOS_LAUNCHER_FILENAME = "AVD Fleet.command"
LINUX_LAUNCHER_FILENAME = "avdfleet.sh"

#: Default daemon port used by the launcher when ``--port`` is not given.
DEFAULT_PORT = 8765
#: Health endpoint polled before the browser is opened.
HEALTH_PATH = "/health"

ASCII = "ascii"
UTF8 = "utf-8"


@dataclass(frozen=True)
class LauncherSpec:
    """One generated launcher file."""

    platform: str
    filename: str
    content: str
    encoding: str
    executable: bool
    description: str = ""

    @property
    def bytes(self) -> bytes:
        return self.content.encode(self.encoding)

    @property
    def is_posix(self) -> bool:
        return self.platform in {"macos", "linux"}

    @property
    def has_bom(self) -> bool:
        return self.bytes.startswith(b"\xef\xbb\xbf")


def _crlf(lines: list[str]) -> str:
    return "\r\n".join(lines) + "\r\n"


def _lf(lines: list[str]) -> str:
    return "\n".join(lines) + "\n"


def _python_finder_sh(rootext: str = "$ROOT") -> list[str]:
    return [
        f'PY="{rootext}/venv/bin/python3"',
        f'[ -x "$PY" ] || PY="{rootext}/venv/bin/python"',
        f'[ -x "$PY" ] || PY="{rootext}/python/bin/python3"',
        f'[ -x "$PY" ] || PY="{rootext}/python/bin/python"',
        '[ -x "$PY" ] || fail "bundled Python runtime not found under '
        f'{rootext}/python or {rootext}/venv"',
    ]


def _posix_env_exports() -> list[str]:
    return [
        'export AVDFLEET_PORTABLE_ROOT="$ROOT"',
        'export AVDFLEET_ROOT="$ROOT"',
        'export AVDFLEET_EDITION="portable"',
        'export AVDFLEET_DATA_DIR="$ROOT/data"',
        'export AVDFLEET_CONFIG_DIR="$ROOT/config"',
        'export AVDFLEET_CACHE_DIR="$ROOT/cache"',
        'export AVDFLEET_LOG_DIR="$ROOT/logs"',
        'export AVDFLEET_SDK_ROOT="$ROOT/sdk"',
        'export AVDFLEET_AVD_HOME="$ROOT/avd"',
        'export ANDROID_HOME="$ROOT/sdk"',
        'export ANDROID_SDK_ROOT="$ROOT/sdk"',
        'export ANDROID_USER_HOME="$ROOT/android"',
        'export ANDROID_PREFS_ROOT="$ROOT/android"',
        'export ANDROID_EMULATOR_HOME="$ROOT/android"',
        'export ANDROID_AVD_HOME="$ROOT/avd"',
        'export PYTHONNOUSERSITE=1',
        'export PYTHONUTF8=1',
        'export TMPDIR="$ROOT/tmp"',
        'export PIP_CACHE_DIR="$ROOT/cache/pip"',
        'export PATH="$ROOT/venv/bin:$ROOT/bin:$ROOT/python/bin:'
        '$ROOT/sdk/cmdline-tools/latest/bin:$ROOT/sdk/platform-tools:'
        '$ROOT/sdk/emulator:$ROOT/node/bin:$PATH"',
    ]


def _fail_function() -> list[str]:
    return [
        'fail() {',
        '    printf \'[AVD Fleet] %s\\n\' "$*" >&2',
        '    if [ -t 0 ]; then',
        "        printf '[AVD Fleet] Press Enter to close...' >&2",
        '        read -r _ || true',
        "    fi",
        "    exit 3",
        "}",
    ]


def linux_launcher(*, version: str = APP_VERSION) -> LauncherSpec:
    """POSIX ``/bin/sh`` launcher for Linux bundles."""
    lines = [
        "#!/bin/sh",
        "# ===========================================================================",
        f"#  AVD Fleet portable launcher (Linux) - generated by avdfleet {version}",
        "#  Run from anywhere: the bundle root is derived from this script's folder,",
        "#  so moving the bundle or renaming the mount point keeps working.",
        "#",
        "#  Options (forwarded to the launcher helper):",
        f"#    --port <n>     daemon port (default {DEFAULT_PORT})",
        "#    --no-browser   do not open the web UI",
        "#  The helper runs: avdfleet serve --portable",
        "# ===========================================================================",
        "set -u",
        'ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)',
        *_fail_function(),
        *_posix_env_exports(),
        *_python_finder_sh(),
        "# Extraction from Windows/zip may have dropped the execute bit.",
        'chmod +x "$ROOT/launchers/avdfleet.sh" 2>/dev/null || true',
        'for helper in "$ROOT/sdk/platform-tools/adb" "$ROOT/sdk/emulator/emulator" \\',
        '    "$ROOT/sdk/cmdline-tools/latest/bin/"*; do',
        '    [ -e "$helper" ] || continue',
        '    [ -x "$helper" ] || chmod +x "$helper" 2>/dev/null || true',
        "done",
        'cd "$ROOT" || fail "cannot enter bundle root $ROOT"',
        'exec "$PY" -m avdfleet.portable.launchers.generator start "$@"',
    ]
    return LauncherSpec(
        platform="linux",
        filename=LINUX_LAUNCHER_FILENAME,
        content=_lf(lines),
        encoding=UTF8,
        executable=True,
        description="Linux POSIX shell launcher",
    )


def macos_launcher(*, version: str = APP_VERSION) -> LauncherSpec:
    """macOS ``.command`` launcher (also catches Gatekeeper quarantine)."""
    lines = [
        "#!/bin/bash",
        "# ===========================================================================",
        f"#  AVD Fleet portable launcher (macOS) - generated by avdfleet {version}",
        "#  Double-click in Finder (Terminal runs it). The bundle root is derived",
        "#  from this script's folder, so moving the bundle keeps working.",
        "#",
        "#  Options (forwarded to the launcher helper):",
        f"#    --port <n>     daemon port (default {DEFAULT_PORT})",
        "#    --no-browser   do not open the web UI",
        "#  The helper runs: avdfleet serve --portable",
        "# ===========================================================================",
        "set -u",
        'ROOT="$(cd "$(dirname "$0")" && pwd -P)"',
        *_fail_function(),
        *_posix_env_exports(),
        *_python_finder_sh(),
        "# Gatekeeper quarantine: check the folder and print the removal command.",
        "if command -v xattr >/dev/null 2>&1; then",
        '    if xattr -p com.apple.quarantine "$ROOT" >/dev/null 2>&1; then',
        "        printf '%s\\n' '[AVD Fleet] This bundle carries the macOS quarantine attribute.'",
        "        printf '%s\\n' '[AVD Fleet] If Gatekeeper blocks the launcher or bundled binaries, run:'",
        '        printf \'    xattr -dr com.apple.quarantine "%s"\\n\' "$ROOT"',
        "        printf '%s\\n' '[AVD Fleet] (Then run this launcher again.)'",
        "    fi",
        "fi",
        'chmod +x "$ROOT/launchers/AVD Fleet.command" 2>/dev/null || true',
        'cd "$ROOT" || fail "cannot enter bundle root $ROOT"',
        'exec "$PY" -m avdfleet.portable.launchers.generator start "$@"',
    ]
    return LauncherSpec(
        platform="macos",
        filename=MACOS_LAUNCHER_FILENAME,
        content=_lf(lines),
        encoding=UTF8,
        executable=True,
        description="macOS terminal launcher with quarantine check",
    )


def windows_launcher(*, version: str = APP_VERSION) -> LauncherSpec:
    """Windows ``.cmd`` launcher with first-run ``Unblock-File``."""
    lines = [
        "@echo off",
        "rem ===========================================================================",
        f"rem  AVD Fleet portable launcher (Windows) - generated by avdfleet {version}",
        "rem  Double-click in Explorer. The bundle root is derived from this script's",
        "rem  folder, so moving the folder or changing drive letters keeps working.",
        "rem",
        "rem  Options (forwarded to the launcher helper):",
        f"rem    --port <n>     daemon port (default {DEFAULT_PORT})",
        "rem    --no-browser   do not open the web UI",
        "rem  The helper runs: avdfleet serve --portable",
        "rem ===========================================================================",
        "setlocal EnableExtensions",
        "set \"EXITCODE=0\"",
        'set "ROOT=%~dp0"',
        'if "%ROOT:~-1%"=="\\" set "ROOT=%ROOT:~0,-1%"',
        'set "AVDFLEET_PORTABLE_ROOT=%ROOT%"',
        'set "AVDFLEET_ROOT=%ROOT%"',
        'set "AVDFLEET_EDITION=portable"',
        'set "AVDFLEET_DATA_DIR=%ROOT%\\data"',
        'set "AVDFLEET_CONFIG_DIR=%ROOT%\\config"',
        'set "AVDFLEET_CACHE_DIR=%ROOT%\\cache"',
        'set "AVDFLEET_LOG_DIR=%ROOT%\\logs"',
        'set "AVDFLEET_SDK_ROOT=%ROOT%\\sdk"',
        'set "AVDFLEET_AVD_HOME=%ROOT%\\avd"',
        'set "ANDROID_HOME=%ROOT%\\sdk"',
        'set "ANDROID_SDK_ROOT=%ROOT%\\sdk"',
        'set "ANDROID_USER_HOME=%ROOT%\\android"',
        'set "ANDROID_PREFS_ROOT=%ROOT%\\android"',
        'set "ANDROID_EMULATOR_HOME=%ROOT%\\android"',
        'set "ANDROID_AVD_HOME=%ROOT%\\avd"',
        'set "PYTHONNOUSERSITE=1"',
        'set "PYTHONUTF8=1"',
        'set "TMP=%ROOT%\\tmp"',
        'set "TEMP=%ROOT%\\tmp"',
        'set "PIP_CACHE_DIR=%ROOT%\\cache\\pip"',
        'set "PATH=%ROOT%\\venv\\Scripts;%ROOT%\\bin;%ROOT%\\python;%ROOT%\\python\\Scripts;%ROOT%\\sdk\\cmdline-tools\\latest\\bin;%ROOT%\\sdk\\platform-tools;%ROOT%\\sdk\\emulator;%PATH%"',
        'set "PY=%ROOT%\\venv\\Scripts\\python.exe"',
        'if not exist "%PY%" set "PY=%ROOT%\\python\\python.exe"',
        'if exist "%PY%" goto :have_python',
        "echo [AVD Fleet] ERROR: bundled Python runtime not found.",
        'echo [AVD Fleet] Expected "%ROOT%\\python\\python.exe" or "%ROOT%\\venv\\Scripts\\python.exe".',
        'set "EXITCODE=3"',
        "goto :fail",
        ":have_python",
        "rem First run only: detect and remove Mark-of-the-Web (Zone.Identifier) streams.",
        'if exist "%ROOT%\\config\\.unblocked" goto :unblocked',
        "echo [AVD Fleet] First run: checking for Mark-of-the-Web (PowerShell 5.1)...",
        'powershell -NoProfile -ExecutionPolicy Bypass -Command "$root=$env:ROOT; if (-not (Test-Path -LiteralPath $root)) { exit 0 }; $pattern=\'^\\.(exe|dll|cmd|bat|ps1|jar|py|js|sh|command)$\'; $blocked=@(Get-ChildItem -LiteralPath $root -Recurse -File -Force -ErrorAction SilentlyContinue | Where-Object { $_.Extension -match $pattern } | Where-Object { Get-Item -LiteralPath $_.FullName -Stream Zone.Identifier -ErrorAction SilentlyContinue }); if ($blocked.Count -gt 0) { $blocked | Unblock-File; Write-Host (\'[AVD Fleet] Removed Mark-of-the-Web from \' + $blocked.Count + \' file(s).\') } else { Write-Host \'[AVD Fleet] No Mark-of-the-Web detected.\' }"',
        "if errorlevel 1 echo [AVD Fleet] WARNING: Mark-of-the-Web check failed; right-click the bundle folder, Properties, Unblock before retrying.",
        'if not exist "%ROOT%\\config" mkdir "%ROOT%\\config" >nul 2>&1',
        '> "%ROOT%\\config\\.unblocked" echo checked',
        ":unblocked",
        'cd /d "%ROOT%"',
        '"%PY%" -m avdfleet.portable.launchers.generator start %*',
        'set "EXITCODE=%ERRORLEVEL%"',
        'if "%EXITCODE%"=="0" exit /b 0',
        "echo.",
        "echo [AVD Fleet] The portable daemon exited with code %EXITCODE%.",
        ":fail",
        'if not "%AVDFLEET_NONINTERACTIVE%"=="1" pause',
        "exit /b %EXITCODE%",
    ]
    return LauncherSpec(
        platform="windows",
        filename=WINDOWS_LAUNCHER_FILENAME,
        content=_crlf(lines),
        encoding=ASCII,
        executable=False,
        description="Windows batch launcher with Unblock-File first run",
    )


def launcher_for_host(host_os: str | None = None, *, version: str = APP_VERSION) -> LauncherSpec:
    """Return the single launcher generated for *host_os* (bundle builds are host-specific)."""
    host = host_os or host_os_name()
    if host == "windows":
        return windows_launcher(version=version)
    if host == "macos":
        return macos_launcher(version=version)
    return linux_launcher(version=version)


def all_launchers(*, version: str = APP_VERSION) -> list[LauncherSpec]:
    """Every launcher template (documentation, tests and cross-host tooling)."""
    return [
        windows_launcher(version=version),
        macos_launcher(version=version),
        linux_launcher(version=version),
    ]


def launcher_filename(host_os: str) -> str:
    return launcher_for_host(host_os).filename


def validate_launcher(spec: LauncherSpec) -> list[str]:
    """Validate encoding/newline rules; returns a list of problems (empty = valid)."""
    problems: list[str] = []
    if not spec.filename:
        problems.append("launcher has no filename")
    content = spec.content
    if spec.platform == "windows":
        if spec.encoding != ASCII:
            problems.append("Windows .cmd launchers must be encoded as ASCII")
        try:
            content.encode(ASCII)
        except UnicodeEncodeError:
            problems.append("Windows .cmd launcher contains non-ASCII characters")
        if "\r\n" not in content:
            problems.append("Windows .cmd launcher must use CRLF line endings")
        if content.replace("\r\n", "").count("\n"):
            problems.append("Windows .cmd launcher has bare LF line endings")
        if content.startswith("\ufeff"):
            problems.append("Windows .cmd launcher must not start with a BOM")
        if spec.executable:
            problems.append("Windows .cmd launchers are run by cmd.exe, not the execute bit")
    else:
        if spec.encoding != UTF8:
            problems.append("POSIX launchers must be UTF-8")
        if spec.has_bom:
            problems.append("POSIX launcher must not start with a UTF-8 BOM (breaks shebang)")
        if not content.startswith("#!"):
            problems.append("POSIX launcher must start with a shebang")
        if "\r" in content:
            problems.append("POSIX launcher must use LF line endings")
        if not spec.executable:
            problems.append("POSIX launcher must be marked executable")
    if not content.endswith("\n"):
        problems.append("launcher must end with a newline")
    if "\0" in content:
        problems.append("launcher contains NUL bytes")
    return problems


def launcher_target_path(root: str | Path, spec: LauncherSpec) -> Path:
    return Path(root) / spec.filename


