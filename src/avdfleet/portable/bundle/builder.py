"""Portable bundle builder.

Copies a prepared component tree (pinned Python runtime, Android SDK tools, web
UI, optional Node/JDK/venv, offline cache) into a destination folder, adds the
default daemon config, portable Studio config and launchers, then writes the
``avdfleet-portable.json`` checksum manifest.  The destination is assembled in a
hidden sibling temp directory and atomically renamed into place, so a failed
build never leaves a half-written bundle.

No network access happens here by design: the builder only consumes
``source_root``/``cache_dir`` inputs and refuses to build when a required
component is absent.  ``offline=True`` additionally requires a populated cache.
"""

