_COPY_IGNORE = shutil.ignore_patterns(
    "__pycache__", "*.pyc", "*.pyo", ".DS_Store", "Thumbs.db", "desktop.ini"
)
_LAYOUT_DIRS = ("bin", "data", "config", "cache", "logs", "tmp", "avd", "android", "studio")


def _utc_stamp() -> str:
    return datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")


def _toml_string(value: str) -> str:
    return json.dumps(str(value))


def _toml_bool(value: bool) -> str:
    return "true" if value else "false"


def default_portable_config(root: str | Path, *, host_os: str | None = None) -> str:
    """Generate the portable daemon ``config.toml`` (absolute paths in the bundle)."""
    paths = PortablePaths.for_root(root)
    lines = [
        "# AVD Fleet portable daemon configuration (generated by 'avdfleet bundle')",
        "# All mutable state lives inside the bundle; relocation rewrites these paths.",
        'edition = "portable"',
        f"portable_root = {_toml_string(paths.root.as_posix())}",
        f"data_dir = {_toml_string(paths.data.as_posix())}",
        f"config_dir = {_toml_string(paths.config.as_posix())}",
        f"cache_dir = {_toml_string(paths.cache.as_posix())}",
        f"log_dir = {_toml_string(paths.logs.as_posix())}",
        f"sdk_root = {_toml_string(paths.sdk.as_posix())}",
        f"avd_home = {_toml_string(paths.avd.as_posix())}",
        "",
        "# loopback-only daemon; the launcher opens the UI after the health check",
        'api_host = "127.0.0.1"',
        f"api_port = {DEFAULT_API_PORT}",
        f"auth_required = {_toml_bool(True)}",
        f"serve_ui = {_toml_bool(True)}",
        f"max_instances = {DEFAULT_MAX_INSTANCES}",
        "",
        "# no telemetry / update checks from a portable bundle",
        f"telemetry = {_toml_bool(False)}",
        f"update_check = {_toml_bool(False)}",
        'log_level = "INFO"',
        "",
    ]
    return "\n".join(lines)


def _copy_component(source: Path, target: Path) -> None:
    """Copy a component tree (dereferences symlinks; strips build caches)."""
    try:
        shutil.copytree(source, target, symlinks=False, ignore=_COPY_IGNORE, dirs_exist_ok=True)
    except OSError as exc:
        raise PortableError(f"Cannot copy bundle component {source} -> {target}: {exc}") from exc


def _prepare_destination(destination: Path, *, force: bool) -> str | None:
    """Validate the destination, returning the planned backup path (if any)."""
    if not destination.exists():
        return None
    if not destination.is_dir():
        raise PortableError(f"Bundle destination exists and is not a directory: {destination}")
    try:
        non_empty = any(destination.iterdir())
    except OSError as exc:
        raise PortableError(f"Cannot inspect bundle destination {destination}: {exc}") from exc
    if not non_empty:
        return None
    if not force:
        raise PortableError(
            f"Bundle destination is not empty: {destination}",
            hint="Build into a new folder, or pass --force to replace it "
            "(the previous bundle is moved to a timestamped backup, not deleted).",
        )
    backup = destination.with_name(f"{destination.name}.backup-{_utc_stamp()}")
    suffix = 1
    while backup.exists():
        backup = destination.with_name(f"{destination.name}.backup-{_utc_stamp()}-{suffix}")
        suffix += 1
    return str(backup)


class PortableBundleBuilder:
    """Implement :class:`avdfleet.core.interfaces.BundleBuilder`.

    ``source_root``/``cache_dir`` point at the prepared component tree (see
    ``bundle/cache.py``); ``filesystem_probe`` is injectable for tests that must
    simulate FAT32/exFAT destinations without such a volume.
    """

    def __init__(
        self,
        *,
        source_root: str | Path | None = None,
        cache_dir: str | Path | None = None,
        version: str = APP_VERSION,
        host_os: str | None = None,
        host_arch: str | None = None,
        python_version: str = "",
        tool_versions: dict[str, str] | None = None,
        filesystem_probe: Callable[[Path], FileSystemInfo] | None = None,
    ) -> None:
        self.source_root = Path(source_root).expanduser() if source_root is not None else None
        self.cache_dir = Path(cache_dir).expanduser() if cache_dir is not None else None
        self.version = version
        self.host_os = host_os
        self.host_arch = host_arch
        self.python_version = python_version
        self.tool_versions = dict(tool_versions or {})
        self.filesystem_probe = filesystem_probe

    # -- protocol methods ---------------------------------------------------
    def build(
        self,
        destination: str | Path,
        *,
        offline: bool = False,
        host_os: str | None = None,
        dry_run: bool = False,
        force: bool = False,
        name: str = "avdfleet-portable",
        warnings: list[str] | None = None,
    ) -> BundleManifest:
        """Build a bundle at *destination* and return its manifest."""
        host = host_os or self.host_os or host_os_name()
        arch = self.host_arch or host_arch_name()
        destination_path = Path(destination).expanduser()
        if not destination_path.is_absolute():
            destination_path = destination_path.resolve()
        build_warnings = list(warnings or [])
        backup = _prepare_destination(destination_path, force=force)
        if backup is not None:
            build_warnings.append(f"existing bundle will be replaced; backup: {backup}")
        parent = destination_path.parent
        filesystem = self._filesystem(destination_path, host)
        if filesystem.kind is FileSystemKind.FAT32:
            raise PortableError(
                f"Refusing to build a portable bundle on FAT32 ({filesystem.mount_point or parent})",
                hint="FAT32 cannot store Android system images/snapshots (>4 GiB) or POSIX "
                "permissions. Use NTFS, APFS, ext4, XFS or Btrfs.",
            )
        if filesystem.kind is FileSystemKind.EXFAT:
            build_warnings.append(
                "Destination is exFAT: large files fit, but POSIX execute bits are lost and "
                "snapshots may be fragile."
            )
        elif filesystem.kind is FileSystemKind.NETWORK:
            build_warnings.append(
                "Destination is a network share: copying/verifying is supported but emulator "
                "I/O will be unreliable."
            )
        plan = resolve_sources(
            source_root=self.source_root,
            cache_dir=self.cache_dir,
            offline=offline,
            host_os=host,
        )
        plan.require()
        build_warnings.extend(plan.warnings)
        if offline:
            build_warnings.append("Offline bundle: all required components come from the cache.")
            build_warnings.append(
                "Offline cache contents are operator-provided: check redistribution/licence rights "
                "before shipping Google system images or other third-party binaries."
            )
        if dry_run:
            return self._preview_manifest(
                destination_path, plan, host, arch, offline, name, build_warnings
            )
        if not parent.is_dir():
            try:
                parent.mkdir(parents=True, exist_ok=True)
            except OSError as exc:
                raise PortableError(f"Cannot create bundle destination parent {parent}: {exc}") from exc

        temp_root: Path | None = None
        try:
            temp_root = Path(tempfile.mkdtemp(prefix=f".{destination_path.name}.build-", dir=str(parent)))
            self._populate(temp_root, plan, host, build_warnings, destination=destination_path)
            python_version = self.python_version or detect_python_version(
                PortablePaths.for_root(temp_root), host_os=host
            )
            entries = [
                file_entry(temp_root, relative) for relative, _path in iter_bundle_files(temp_root)
            ]
            tool_versions = {
                "avdfleet": self.version,
                **({"python": python_version} if python_version else {}),
                **self.tool_versions,
            }
            manifest = build_manifest(
                entries,
                root=destination_path,
                name=name,
                version=self.version,
                host_os=host,
                host_arch=arch,
                offline=offline,
                python_version=python_version,
                tool_versions=tool_versions,
                warnings=_dedupe(build_warnings),
            )
            write_manifest(temp_root, manifest)
            self._install(temp_root, destination_path, backup)
            temp_root = None
            if backup is not None:
                manifest.warnings = _dedupe([*manifest.warnings, f"previous bundle backed up to {backup}"])
                write_manifest(destination_path, manifest)
            return manifest
        except OSError as exc:
            raise PortableError(f"Failed to build portable bundle at {destination_path}: {exc}") from exc
        finally:
            if temp_root is not None and temp_root.exists():
                shutil.rmtree(temp_root, ignore_errors=True)

    def verify(self, root: str | Path) -> BundleManifest:
        """Verify the bundle; raises :class:`BundleVerificationError` on mismatch."""
        report = self.verify_report(root)
        if not report.ok or report.manifest is None:
            raise BundleVerificationError(report)
        return report.manifest

    def verify_report(self, root: str | Path) -> VerifyReport:
        return verify_bundle(root)

    def inspect(self, root: str | Path) -> BundleManifest:
        """Read the manifest without hashing the bundle."""
        return read_manifest(root)

    def inspect_summary(self, root: str | Path) -> dict[str, Any]:
        return inspect_bundle(root).to_dict()

    def inspect_bundle(self, root: str | Path) -> BundleInspection:
        return inspect_bundle(root)

    def manifest_summary(self, root: str | Path) -> dict[str, Any]:
        return manifest_summary(read_manifest(root))

    # -- internals ----------------------------------------------------------
    def _filesystem(self, destination: Path, host: str) -> FileSystemInfo:
        probe = self.filesystem_probe
        target = destination if destination.exists() else destination.parent
        return detect_filesystem(target, host_os=host, probe=probe)

    def _preview_manifest(
        self,
        destination: Path,
        plan: SourcePlan,
        host: str,
        arch: str,
        offline: bool,
        name: str,
        build_warnings: list[str],
    ) -> BundleManifest:
        warnings = _dedupe(
            [
                *build_warnings,
                "dry run: no files were copied and no manifest was written",
                "planned components: " + ", ".join(sorted(plan.components)),
            ]
        )
        return build_manifest(
            [],
            root=destination,
            name=name,
            version=self.version,
            host_os=host,
            host_arch=arch,
            offline=offline,
            python_version=self.python_version,
            tool_versions={"avdfleet": self.version, **self.tool_versions},
            warnings=warnings,
        )

    def _populate(
        self,
        root: Path,
        plan: SourcePlan,
        host: str,
        build_warnings: list[str],
        *,
        destination: Path,
    ) -> None:
        for directory in _LAYOUT_DIRS:
            (root / directory).mkdir(parents=True, exist_ok=True)
        for component, source in sorted(plan.components.items()):
            if component == "studio":
                # Static studio config is regenerated below with destination paths.
                continue
            _copy_component(source, root / component)
        if plan.downloads is not None:
            _copy_component(plan.downloads, root / "cache" / "downloads")
        # Content must reference the *final* destination root, not the temp build dir.
        (root / "config" / "config.toml").write_text(
            default_portable_config(destination, host_os=host), encoding="utf-8", newline="\n"
        )
        studio_dir = root / "studio"
        studio_dir.mkdir(parents=True, exist_ok=True)
        (studio_dir / STUDIO_PROPERTIES_FILENAME).write_text(
            build_studio_properties(destination), encoding="utf-8", newline="\n"
        )
        (studio_dir / STUDIO_VMOPTIONS_FILENAME).write_text(
            build_studio_vmoptions(destination), encoding="utf-8", newline="\n"
        )
        write_launchers(root, host_os=host, version=self.version)
        venv_dir = root / "venv"
        if venv_dir.is_dir():
            prepared_roots = discover_venv_old_roots(venv_dir, host_os=host)
            if prepared_roots:
                repair = repair_venv(
                    venv_dir,
                    old_roots=prepared_roots,
                    current_root=destination,
                    rebuild=False,
                    host_os=host,
                )
                build_warnings.extend(repair.warnings)
                if repair.rewritten:
                    build_warnings.append(
                        f"rewrote {len(repair.rewritten)} prepared virtualenv path(s) for the "
                        "bundle destination"
                    )
        for optional in plan.missing_optional:
            build_warnings.append(f"optional component missing from the bundle: {optional}")
        if not (root / "ui" / "index.html").is_file():
            build_warnings.append(
                "ui/index.html is missing; the daemon will run API-only until the UI is built"
            )

    def _install(self, temp_root: Path, destination: Path, backup: str | None) -> None:
        try:
            if destination.exists():
                if backup is not None:
                    os.replace(destination, Path(backup))
                else:
                    destination.rmdir()
            os.replace(temp_root, destination)
        except OSError as exc:
            # Best effort rollback so a failed rename cannot lose the old bundle.
            if backup is not None and Path(backup).exists() and not destination.exists():
                try:
                    os.replace(Path(backup), destination)
                except OSError:  # pragma: no cover - rollback failure
                    pass
            raise PortableError(f"Cannot move the built bundle into {destination}: {exc}") from exc


def _dedupe(values: list[str]) -> list[str]:
    seen: set[str] = set()
    result: list[str] = []
    for value in values:
        if value and value not in seen:
            seen.add(value)
            result.append(value)
    return result
