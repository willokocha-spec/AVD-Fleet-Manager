class MutableClock:
    def __init__(self, value: datetime = FIXED_NOW) -> None:
        self.value = value

    def __call__(self) -> datetime:
        return self.value

    def advance(self, seconds: int) -> None:
        from datetime import timedelta

        self.value = self.value + timedelta(seconds=seconds)


